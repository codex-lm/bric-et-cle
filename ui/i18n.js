const DICOS = { fr: FR, en: EN };
let langue = 'en';

export function setLangue(l) {
  langue = DICOS[l] ? l : 'en';
  document.documentElement.lang = langue;
}
export const getLangue = () => langue;

/** Texte traduit ; {x} est remplacé par params.x. */
export function t(cle, params = {}) {
  const s = DICOS[langue][cle] ?? DICOS.fr[cle] ?? cle;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] !== undefined ? params[k] : `{${k}}`));
}

/** Champ multilingue d'un fichier de niveau : {fr, en}. */
export const tr = (o) => (o == null ? '' : typeof o === 'string' ? o : o[langue] ?? o.fr);
